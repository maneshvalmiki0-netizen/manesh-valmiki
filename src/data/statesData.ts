// Helper to get total 36 entities combined
export function getAllEntitiesSummary() {
  const fullList = allStates.map(s => ({
    id: s.id,
    slug: s.slug,
    name: s.name,
    hindiName: s.hindiName || '',
    type: s.type,
    region: s.region,
    capital: s.capital,
    languages: s.officialLanguages,
    tagline: s.tagline,
    culturalHighlight: s.overview.slice(0, 150) + '...',
    isFullProfile: true,
  }));

  const compactList = compactEntities.map(c => ({
    id: c.id,
    slug: c.slug,
    name: c.name,
    hindiName: c.hindiName,
    type: c.type,
    region: c.region,
    capital: c.capital,
    languages: c.languages,
    tagline: c.tagline,
    culturalHighlight: c.culturalHighlight,
    isFullProfile: false,
  }));

  return [...fullList, ...compactList];
}

